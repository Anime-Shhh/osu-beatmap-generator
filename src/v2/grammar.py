"""Grammar-constrained sparse symbolic planning for osu!standard.

The old v2 prototype treated every beat-grid slot as two independent Bernoulli
lanes.  That has no stable ordering, permits illegal same-tick objects, and
cannot express a variable number of events.  This module provides the compact
bar-local symbolic language used by the new planner instead.  Geometry is
intentionally absent here: it is generated by the separate active-event path
refiner after this grammar has produced a legal temporal/object plan.

The codec is deliberately conservative.  It is a *planner* representation,
not a lossy replacement for :class:`src.v2.spec.MapSpec`; the compiler keeps
the complete slider/control-point data separately.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum, IntEnum
from fractions import Fraction
from typing import Iterable, Mapping, Sequence

from .events import BeatEvent, EventKind


# These cover normal binary, triplet, and fine ranked-map snap families.  A
# generated object may retain a small residual, but validation later decides
# whether that residual is justified rather than silently treating it as a
# normal fixed-grid event.
# 1/96 is deliberately available as an internal rare-snap class. It prevents
# an exact 1/96 source object from being silently rounded to a coarser 1/48
# location before the bounded microtiming residual can be represented.
SNAP_DENOMINATORS: tuple[int, ...] = (1, 2, 3, 4, 6, 8, 12, 16, 24, 32, 48, 96)
MAX_BAR_BEATS = 12  # Covers the common and unusual meters without unbounded vocabularies.
MAX_ANCHORS = 8
MAX_REPEATS = 8
# Long objects may cross a bar boundary.  Duration is therefore bounded
# separately from a bar's event offsets instead of being silently clipped to
# the current meter.  At 1/16-beat resolution this admits 128 beats (roughly a
# minute at moderate tempos); longer source examples are surfaced to the data
# audit rather than mislabeled as short objects.
MAX_DURATION_BEATS = 128
DURATION_TICKS_PER_BEAT = 16
# A small residual retains intentional source microtiming without allowing the
# planner to evade its rhythmic grammar. Eight 1/1536-beat steps span +/-1/192
# beat, exactly the strict MapSpec snap tolerance used for generated drafts.
RESIDUAL_TICKS_PER_BEAT = 1536
MAX_RESIDUAL_STEPS = 8
# The least common multiple of the supported denominators.  A 1/48 internal
# grid cannot represent a 1/32 location exactly; 96 ticks per beat can.
TICKS_PER_BEAT = 96
RESIDUAL_UNITS_PER_OFFSET_TICK = RESIDUAL_TICKS_PER_BEAT // TICKS_PER_BEAT
if RESIDUAL_TICKS_PER_BEAT % TICKS_PER_BEAT:
    raise RuntimeError("residual resolution must be an integer multiple of the offset grid")


class TokenFamily(str, Enum):
    CONTROL = "control"
    OFFSET = "offset"
    SNAP = "snap"
    RESIDUAL = "residual"
    KIND = "kind"
    COMBO = "combo"
    HIT_SOUND = "hit_sound"
    DURATION = "duration"
    CURVE = "curve"
    REPEATS = "repeats"
    ANCHORS = "anchors"


class DecodePhase(IntEnum):
    START = 0
    BETWEEN_EVENTS = 1
    EVENT_OFFSET = 2
    EVENT_SNAP = 3
    EVENT_RESIDUAL = 4
    EVENT_KIND = 5
    EVENT_COMBO = 6
    EVENT_HIT_SOUND = 7
    SLIDER_DURATION = 8
    SLIDER_CURVE = 9
    SLIDER_REPEATS = 10
    SLIDER_ANCHORS = 11
    SPINNER_DURATION = 12


@dataclass(frozen=True)
class PlannerEvent:
    """A geometry-free event emitted by a bar-local symbolic decoder."""

    beat_position: float
    kind: EventKind
    new_combo: bool = False
    hit_sound: int = 0
    duration_beats: float = 0.0
    curve_type: str = "B"
    slider_repeats: int = 1
    anchor_count: int = 0


@dataclass(frozen=True)
class GrammarState:
    """State needed to reject impossible next token families."""

    phase: DecodePhase = DecodePhase.START
    last_offset_tick: int = -1
    last_time_units: int = -1_000_000_000
    current_offset_tick: int | None = None
    current_residual_steps: int | None = None
    current_kind: EventKind | None = None


class EventVocabulary:
    """Fixed, inspectable token vocabulary for a sparse event plan.

    Offset tokens use 1/96 beat ticks inside a bar and a bounded 1/1536-beat
    residual carries only microtiming. The selected rational snap token carries
    the human-readable divisibility class, which prevents the model from
    learning that triplets and binary rhythms are indistinguishable integer
    locations. The grammar verifies that a base offset is compatible with that
    class before accepting it.
    """

    def __init__(self, *, max_bar_beats: int = MAX_BAR_BEATS):
        if max_bar_beats < 1:
            raise ValueError("max_bar_beats must be positive")
        self.max_bar_beats = int(max_bar_beats)
        names: list[str] = ["BOS", "EOS", "EVENT"]
        names.extend(f"offset:{tick}" for tick in range(self.max_bar_beats * TICKS_PER_BEAT))
        names.extend(f"snap:{denominator}" for denominator in SNAP_DENOMINATORS)
        names.extend(f"residual:{steps}" for steps in range(-MAX_RESIDUAL_STEPS, MAX_RESIDUAL_STEPS + 1))
        names.extend(f"kind:{kind.name.lower()}" for kind in EventKind)
        names.extend(("combo:0", "combo:1"))
        names.extend(f"hit_sound:{value}" for value in range(16))
        # Duration is measured in 1/16 beat units.  Its bound is independent
        # of the bar offset vocabulary because sliders/spinners can continue
        # beyond the bar in which their start object is planned.
        names.extend(
            f"duration:{tick}"
            for tick in range(1, MAX_DURATION_BEATS * DURATION_TICKS_PER_BEAT + 1)
        )
        names.extend(f"curve:{curve}" for curve in ("B", "L", "P", "C"))
        names.extend(f"repeats:{count}" for count in range(1, MAX_REPEATS + 1))
        names.extend(f"anchors:{count}" for count in range(1, MAX_ANCHORS + 1))
        self._names = tuple(names)
        self._ids = {name: index for index, name in enumerate(self._names)}

    def __len__(self) -> int:
        return len(self._names)

    @property
    def bos_id(self) -> int:
        return self._ids["BOS"]

    @property
    def eos_id(self) -> int:
        return self._ids["EOS"]

    @property
    def event_id(self) -> int:
        return self._ids["EVENT"]

    def id_for(self, name: str) -> int:
        return self._ids[name]

    def name_for(self, token_id: int) -> str:
        if not 0 <= int(token_id) < len(self._names):
            raise ValueError(f"unknown planner token id: {token_id}")
        return self._names[int(token_id)]

    def family_of(self, token_id: int) -> TokenFamily:
        name = self.name_for(token_id)
        if name in {"BOS", "EOS", "EVENT"}:
            return TokenFamily.CONTROL
        prefix = name.split(":", maxsplit=1)[0]
        return TokenFamily(prefix)

    def ids_for_family(self, family: TokenFamily) -> tuple[int, ...]:
        return tuple(index for index in range(len(self)) if self.family_of(index) == family)

    def offset_tick(self, token_id: int) -> int:
        name = self.name_for(token_id)
        if not name.startswith("offset:"):
            raise ValueError(f"expected offset token, got {name}")
        return int(name.split(":", maxsplit=1)[1])

    def snap_denominator(self, token_id: int) -> int:
        name = self.name_for(token_id)
        if not name.startswith("snap:"):
            raise ValueError(f"expected snap token, got {name}")
        return int(name.split(":", maxsplit=1)[1])

    def residual_steps(self, token_id: int) -> int:
        name = self.name_for(token_id)
        if not name.startswith("residual:"):
            raise ValueError(f"expected residual token, got {name}")
        return int(name.split(":", maxsplit=1)[1])


class EventGrammar:
    """Finite-state grammar and semantic checks for sparse event tokens."""

    def __init__(self, vocabulary: EventVocabulary):
        self.vocabulary = vocabulary

    def allowed_ids(self, state: GrammarState) -> tuple[int, ...]:
        vocab = self.vocabulary
        if state.phase == DecodePhase.START:
            return (vocab.bos_id,)
        if state.phase == DecodePhase.BETWEEN_EVENTS:
            has_next_offset = any(
                vocab.offset_tick(token_id) > state.last_offset_tick
                for token_id in vocab.ids_for_family(TokenFamily.OFFSET)
            )
            return (vocab.eos_id, vocab.event_id) if has_next_offset else (vocab.eos_id,)
        if state.phase == DecodePhase.EVENT_OFFSET:
            return tuple(
                token_id
                for token_id in vocab.ids_for_family(TokenFamily.OFFSET)
                if vocab.offset_tick(token_id) > state.last_offset_tick
            )
        if state.phase == DecodePhase.EVENT_SNAP:
            if state.current_offset_tick is None:
                raise AssertionError("snap phase needs an offset tick")
            return tuple(
                token_id
                for token_id in vocab.ids_for_family(TokenFamily.SNAP)
                if state.current_offset_tick % (TICKS_PER_BEAT // vocab.snap_denominator(token_id)) == 0
            )
        if state.phase == DecodePhase.EVENT_RESIDUAL:
            if state.current_offset_tick is None:
                raise AssertionError("residual phase needs an offset tick")
            base_units = state.current_offset_tick * RESIDUAL_UNITS_PER_OFFSET_TICK
            return tuple(
                token_id
                for token_id in vocab.ids_for_family(TokenFamily.RESIDUAL)
                if base_units + vocab.residual_steps(token_id) > state.last_time_units
            )
        if state.phase == DecodePhase.EVENT_KIND:
            return vocab.ids_for_family(TokenFamily.KIND)
        if state.phase == DecodePhase.EVENT_COMBO:
            return vocab.ids_for_family(TokenFamily.COMBO)
        if state.phase == DecodePhase.EVENT_HIT_SOUND:
            return vocab.ids_for_family(TokenFamily.HIT_SOUND)
        if state.phase == DecodePhase.SLIDER_DURATION:
            return vocab.ids_for_family(TokenFamily.DURATION)
        if state.phase == DecodePhase.SLIDER_CURVE:
            return vocab.ids_for_family(TokenFamily.CURVE)
        if state.phase == DecodePhase.SLIDER_REPEATS:
            return vocab.ids_for_family(TokenFamily.REPEATS)
        if state.phase == DecodePhase.SLIDER_ANCHORS:
            return vocab.ids_for_family(TokenFamily.ANCHORS)
        if state.phase == DecodePhase.SPINNER_DURATION:
            return vocab.ids_for_family(TokenFamily.DURATION)
        raise AssertionError(f"unsupported grammar phase {state.phase}")

    def allowed_ids_for_bar(self, state: GrammarState, *, meter: float) -> tuple[int, ...]:
        """Apply meter bounds to the dynamic subset used during generation.

        The fixed grammar knows the largest supported bar vocabulary but not a
        particular 3/4, 4/4, or fractional-meter target. Without this extra
        mask an otherwise legal token could decode outside the requested bar
        and abort audio-only sampling after a costly model rollout.
        """

        if not 0.0 < float(meter) <= self.vocabulary.max_bar_beats:
            raise ValueError(f"bar length must be within (0, {self.vocabulary.max_bar_beats}]")
        allowed = self.allowed_ids(state)
        if state.phase == DecodePhase.BETWEEN_EVENTS:
            has_next_offset = any(
                self.vocabulary.offset_tick(token_id) / TICKS_PER_BEAT < float(meter)
                for token_id in self.allowed_ids(
                    GrammarState(DecodePhase.EVENT_OFFSET, last_offset_tick=state.last_offset_tick)
                )
            )
            return (self.vocabulary.eos_id, self.vocabulary.event_id) if has_next_offset else (self.vocabulary.eos_id,)
        if state.phase == DecodePhase.EVENT_OFFSET:
            return tuple(
                token_id
                for token_id in allowed
                if self.vocabulary.offset_tick(token_id) / TICKS_PER_BEAT < float(meter)
            )
        if state.phase == DecodePhase.EVENT_RESIDUAL:
            if state.current_offset_tick is None:
                raise AssertionError("residual phase needs an offset tick")
            base = state.current_offset_tick / TICKS_PER_BEAT
            return tuple(
                token_id
                for token_id in allowed
                if 0.0 <= base + self.vocabulary.residual_steps(token_id) / RESIDUAL_TICKS_PER_BEAT < float(meter)
            )
        return allowed

    @staticmethod
    def _current_time_units(state: GrammarState) -> int:
        if state.current_offset_tick is None or state.current_residual_steps is None:
            raise AssertionError("completed event needs offset and residual state")
        return state.current_offset_tick * RESIDUAL_UNITS_PER_OFFSET_TICK + state.current_residual_steps

    def transition(self, state: GrammarState, token_id: int) -> GrammarState:
        vocab = self.vocabulary
        allowed = self.allowed_ids(state)
        if token_id not in allowed:
            raise ValueError(
                f"token {vocab.name_for(token_id)!r} is invalid in phase {state.phase.name}"
            )
        name = vocab.name_for(token_id)
        if state.phase == DecodePhase.START:
            return GrammarState(
                DecodePhase.BETWEEN_EVENTS,
                last_offset_tick=state.last_offset_tick,
                last_time_units=state.last_time_units,
            )
        if state.phase == DecodePhase.BETWEEN_EVENTS:
            if token_id == vocab.eos_id:
                return GrammarState(
                    DecodePhase.START,
                    last_offset_tick=state.last_offset_tick,
                    last_time_units=state.last_time_units,
                )
            return GrammarState(
                DecodePhase.EVENT_OFFSET,
                last_offset_tick=state.last_offset_tick,
                last_time_units=state.last_time_units,
            )
        if state.phase == DecodePhase.EVENT_OFFSET:
            return GrammarState(
                DecodePhase.EVENT_SNAP,
                last_offset_tick=state.last_offset_tick,
                last_time_units=state.last_time_units,
                current_offset_tick=vocab.offset_tick(token_id),
            )
        if state.phase == DecodePhase.EVENT_SNAP:
            assert state.current_offset_tick is not None
            denominator = vocab.snap_denominator(token_id)
            # A denominator is valid only if the offset is a multiple of its
            # 1/denominator step.  E.g. an 1/3 token cannot label a 1/16 tick.
            step = TICKS_PER_BEAT // denominator
            if state.current_offset_tick % step:
                raise ValueError("snap denominator is incompatible with offset tick")
            return GrammarState(
                DecodePhase.EVENT_RESIDUAL,
                last_offset_tick=state.last_offset_tick,
                last_time_units=state.last_time_units,
                current_offset_tick=state.current_offset_tick,
            )
        if state.phase == DecodePhase.EVENT_RESIDUAL:
            return GrammarState(
                DecodePhase.EVENT_KIND,
                last_offset_tick=state.last_offset_tick,
                last_time_units=state.last_time_units,
                current_offset_tick=state.current_offset_tick,
                current_residual_steps=vocab.residual_steps(token_id),
            )
        if state.phase == DecodePhase.EVENT_KIND:
            kind_name = name.split(":", maxsplit=1)[1].upper()
            return GrammarState(
                DecodePhase.EVENT_COMBO,
                last_offset_tick=state.last_offset_tick,
                last_time_units=state.last_time_units,
                current_offset_tick=state.current_offset_tick,
                current_residual_steps=state.current_residual_steps,
                current_kind=EventKind[kind_name],
            )
        if state.phase == DecodePhase.EVENT_COMBO:
            return GrammarState(
                DecodePhase.EVENT_HIT_SOUND,
                last_offset_tick=state.last_offset_tick,
                last_time_units=state.last_time_units,
                current_offset_tick=state.current_offset_tick,
                current_residual_steps=state.current_residual_steps,
                current_kind=state.current_kind,
            )
        if state.phase == DecodePhase.EVENT_HIT_SOUND:
            assert state.current_kind is not None
            next_phase = {
                EventKind.CIRCLE: DecodePhase.BETWEEN_EVENTS,
                EventKind.SLIDER: DecodePhase.SLIDER_DURATION,
                EventKind.SPINNER: DecodePhase.SPINNER_DURATION,
            }[state.current_kind]
            if next_phase == DecodePhase.BETWEEN_EVENTS:
                # Offset zero is a valid first object position.  Do not use
                # ``or -1`` here: zero is falsy and would accidentally allow
                # a second event at the same tick.
                return GrammarState(
                    DecodePhase.BETWEEN_EVENTS,
                    last_offset_tick=(
                        state.current_offset_tick if state.current_offset_tick is not None else -1
                    ),
                    last_time_units=self._current_time_units(state),
                )
            return GrammarState(
                next_phase,
                last_offset_tick=state.last_offset_tick,
                last_time_units=state.last_time_units,
                current_offset_tick=state.current_offset_tick,
                current_residual_steps=state.current_residual_steps,
                current_kind=state.current_kind,
            )
        if state.phase == DecodePhase.SLIDER_DURATION:
            return GrammarState(
                DecodePhase.SLIDER_CURVE,
                last_offset_tick=state.last_offset_tick,
                last_time_units=state.last_time_units,
                current_offset_tick=state.current_offset_tick,
                current_residual_steps=state.current_residual_steps,
                current_kind=state.current_kind,
            )
        if state.phase == DecodePhase.SLIDER_CURVE:
            return GrammarState(
                DecodePhase.SLIDER_REPEATS,
                last_offset_tick=state.last_offset_tick,
                last_time_units=state.last_time_units,
                current_offset_tick=state.current_offset_tick,
                current_residual_steps=state.current_residual_steps,
                current_kind=state.current_kind,
            )
        if state.phase == DecodePhase.SLIDER_REPEATS:
            return GrammarState(
                DecodePhase.SLIDER_ANCHORS,
                last_offset_tick=state.last_offset_tick,
                last_time_units=state.last_time_units,
                current_offset_tick=state.current_offset_tick,
                current_residual_steps=state.current_residual_steps,
                current_kind=state.current_kind,
            )
        if state.phase in {DecodePhase.SLIDER_ANCHORS, DecodePhase.SPINNER_DURATION}:
            return GrammarState(
                DecodePhase.BETWEEN_EVENTS,
                last_offset_tick=(
                    state.current_offset_tick if state.current_offset_tick is not None else -1
                ),
                last_time_units=self._current_time_units(state),
            )
        raise AssertionError(f"unsupported grammar phase {state.phase}")


def _snap_fraction(offset_beats: float) -> tuple[int, int]:
    """Return the closest allowed rational position inside a bar."""

    target = Fraction(float(offset_beats)).limit_denominator(96)
    choices = [Fraction(round(float(offset_beats) * denominator), denominator) for denominator in SNAP_DENOMINATORS]
    choice = min(choices, key=lambda value: abs(float(value - target)))
    return choice.numerator, choice.denominator


class BarEventCodec:
    """Encode/decode sparse events for one meter-aware bar.

    Coordinates and slider anchors stay outside the token sequence.  The
    returned :class:`PlannerEvent` list is the contract handed to geometry
    diffusion and the MapSpec compiler.
    """

    def __init__(self, vocabulary: EventVocabulary | None = None):
        self.vocabulary = vocabulary or EventVocabulary()
        self.grammar = EventGrammar(self.vocabulary)

    def encode(
        self,
        events: Iterable[BeatEvent],
        *,
        bar_start_beat: float,
        meter: float,
    ) -> list[int]:
        if not 0.0 < float(meter) <= self.vocabulary.max_bar_beats:
            raise ValueError(f"bar length must be within (0, {self.vocabulary.max_bar_beats}]")
        selected = [
            event
            for event in sorted(events, key=lambda value: (value.beat_position, value.source_object_index))
            if bar_start_beat <= event.beat_position < bar_start_beat + meter
        ]
        tokens = [self.vocabulary.bos_id]
        state = self.grammar.transition(GrammarState(), tokens[0])
        for event in selected:
            offset = event.beat_position - bar_start_beat
            numerator, denominator = _snap_fraction(offset)
            tick = int(round(float(Fraction(numerator, denominator) * TICKS_PER_BEAT)))
            event_tokens = [
                self.vocabulary.event_id,
                self.vocabulary.id_for(f"offset:{tick}"),
                self.vocabulary.id_for(f"snap:{denominator}"),
                self.vocabulary.id_for(
                    f"residual:{self._residual_steps(offset, float(tick) / TICKS_PER_BEAT)}"
                ),
                self.vocabulary.id_for(f"kind:{event.kind.name.lower()}"),
                self.vocabulary.id_for(f"combo:{int(event.new_combo)}"),
                self.vocabulary.id_for(f"hit_sound:{int(event.hit_sound) & 15}"),
            ]
            if event.kind == EventKind.SLIDER:
                duration = max((event.end_beat or event.beat_position) - event.beat_position, 1.0 / 16.0)
                duration_tick = max(1, int(round(duration * DURATION_TICKS_PER_BEAT)))
                if duration_tick > MAX_DURATION_BEATS * DURATION_TICKS_PER_BEAT:
                    raise ValueError("slider duration exceeds sparse planner vocabulary")
                anchors = min(MAX_ANCHORS, max(1, len(event.control_points)))
                event_tokens.extend((
                    self.vocabulary.id_for(f"duration:{duration_tick}"),
                    self.vocabulary.id_for(f"curve:{event.curve_type.upper()}"),
                    self.vocabulary.id_for(f"repeats:{min(MAX_REPEATS, max(1, event.slider_repeats))}"),
                    self.vocabulary.id_for(f"anchors:{anchors}"),
                ))
            elif event.kind == EventKind.SPINNER:
                duration = max((event.end_beat or event.beat_position) - event.beat_position, 1.0 / 16.0)
                duration_tick = max(1, int(round(duration * DURATION_TICKS_PER_BEAT)))
                if duration_tick > MAX_DURATION_BEATS * DURATION_TICKS_PER_BEAT:
                    raise ValueError("spinner duration exceeds sparse planner vocabulary")
                event_tokens.append(self.vocabulary.id_for(f"duration:{duration_tick}"))
            for token in event_tokens:
                state = self.grammar.transition(state, token)
            tokens.extend(event_tokens)
        state = self.grammar.transition(state, self.vocabulary.eos_id)
        tokens.append(self.vocabulary.eos_id)
        return tokens

    def decode(
        self,
        tokens: Sequence[int],
        *,
        bar_start_beat: float,
        meter: float,
    ) -> list[PlannerEvent]:
        if not tokens:
            return []
        state = GrammarState()
        parsed: list[PlannerEvent] = []
        fields: dict[str, int | str] = {}
        for token in tokens:
            previous = state
            state = self.grammar.transition(state, int(token))
            name = self.vocabulary.name_for(int(token))
            if previous.phase == DecodePhase.EVENT_OFFSET:
                fields["offset"] = self.vocabulary.offset_tick(int(token))
            elif previous.phase == DecodePhase.EVENT_SNAP:
                fields["snap"] = self.vocabulary.snap_denominator(int(token))
            elif previous.phase == DecodePhase.EVENT_RESIDUAL:
                fields["residual"] = self.vocabulary.residual_steps(int(token))
            elif previous.phase == DecodePhase.EVENT_KIND:
                fields["kind"] = name.split(":", maxsplit=1)[1]
            elif previous.phase == DecodePhase.EVENT_COMBO:
                fields["combo"] = int(name.endswith(":1"))
            elif previous.phase == DecodePhase.EVENT_HIT_SOUND:
                fields["hitsound"] = int(name.split(":", maxsplit=1)[1])
                if state.phase == DecodePhase.BETWEEN_EVENTS:
                    parsed.append(self._event_from_fields(fields, bar_start_beat))
                    fields = {}
            elif previous.phase == DecodePhase.SLIDER_DURATION:
                fields["duration"] = int(name.split(":", maxsplit=1)[1])
            elif previous.phase == DecodePhase.SLIDER_CURVE:
                fields["curve"] = name.split(":", maxsplit=1)[1]
            elif previous.phase == DecodePhase.SLIDER_REPEATS:
                fields["repeats"] = int(name.split(":", maxsplit=1)[1])
            elif previous.phase == DecodePhase.SLIDER_ANCHORS:
                fields["anchors"] = int(name.split(":", maxsplit=1)[1])
                parsed.append(self._event_from_fields(fields, bar_start_beat))
                fields = {}
            elif previous.phase == DecodePhase.SPINNER_DURATION:
                fields["duration"] = int(name.split(":", maxsplit=1)[1])
                parsed.append(self._event_from_fields(fields, bar_start_beat))
                fields = {}
        if state.phase != DecodePhase.START:
            raise ValueError("bar token sequence does not terminate with EOS")
        if any(
            event.beat_position < bar_start_beat
            or event.beat_position >= bar_start_beat + float(meter)
            for event in parsed
        ):
            raise ValueError("decoded event lies outside the requested bar meter")
        return parsed

    def event_context_positions(self, tokens: Sequence[int]) -> tuple[int, ...]:
        """Return the final token position for each complete planned event.

        Geometry must see the sampled kind, duration, curve, repeat, and anchor
        fields. Using the earlier ``EVENT`` marker position would make a
        causal decoder condition geometry only on the fact that an event starts,
        not on its completed symbolic plan.
        """

        state = GrammarState()
        positions: list[int] = []
        for index, token in enumerate(tokens):
            previous = state
            state = self.grammar.transition(state, int(token))
            if (
                state.phase == DecodePhase.BETWEEN_EVENTS
                and previous.phase
                in {
                    DecodePhase.EVENT_HIT_SOUND,
                    DecodePhase.SLIDER_ANCHORS,
                    DecodePhase.SPINNER_DURATION,
                }
            ):
                positions.append(index)
        if state.phase != DecodePhase.START:
            raise ValueError("bar token sequence does not terminate with EOS")
        return tuple(positions)

    @staticmethod
    def _residual_steps(offset_beats: float, base_beats: float) -> int:
        residual = float(offset_beats) - float(base_beats)
        steps = int(round(residual * RESIDUAL_TICKS_PER_BEAT))
        if abs(steps) > MAX_RESIDUAL_STEPS:
            raise ValueError(
                "event timing differs by more than +/-1/192 beat from the sparse snap vocabulary; "
                "audit or represent it with an explicit future timing-residual extension"
            )
        reconstruction = base_beats + steps / RESIDUAL_TICKS_PER_BEAT
        if abs(float(offset_beats) - reconstruction) > 0.5 / RESIDUAL_TICKS_PER_BEAT + 1e-9:
            raise AssertionError("residual quantization exceeds its documented half-step bound")
        return steps

    @staticmethod
    def _event_from_fields(fields: Mapping[str, int | str], bar_start_beat: float) -> PlannerEvent:
        required = {"offset", "residual", "kind", "combo", "hitsound"}
        if not required.issubset(fields):
            raise ValueError(f"incomplete event fields: missing {sorted(required - set(fields))}")
        kind = EventKind[str(fields["kind"]).upper()]
        duration = float(int(fields.get("duration", 0))) / DURATION_TICKS_PER_BEAT
        return PlannerEvent(
            beat_position=(
                bar_start_beat
                + float(int(fields["offset"])) / float(TICKS_PER_BEAT)
                + float(int(fields["residual"])) / float(RESIDUAL_TICKS_PER_BEAT)
            ),
            kind=kind,
            new_combo=bool(fields["combo"]),
            hit_sound=int(fields["hitsound"]),
            duration_beats=duration,
            curve_type=str(fields.get("curve", "B")),
            slider_repeats=int(fields.get("repeats", 1)),
            anchor_count=int(fields.get("anchors", 0)),
        )
